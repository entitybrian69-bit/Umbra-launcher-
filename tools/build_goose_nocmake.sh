#!/usr/bin/env bash
# Build the pinned Goose compiler WITHOUT cmake.
#
# Why this exists: the development sandbox for this project has no cmake, so
# tools/pin_goose.sh gets as far as checking the source out and then stops. CI and
# the release use the cmake build; this is the same compiler built by hand, with
# the three files cmake would have generated written by this script instead:
#
#   version/goose_version.h          (cmake/version.cmake)
#   generated/builtin_packages.h     (cmake/package.cmake; blessed table, no
#                                     packages compiled in)
#   include/config.h                 (cmake/libtcc.cmake)
#   jit_symbols.inc                  (the GS_API symbol table cmake scrapes out of
#                                     src/runtime/*.h)
#
# If any of the files cmake generates changes shape upstream, this script is what
# notices: it builds the compiler, and the compiler is what generates Umbra's core
# in every other workflow.
#
# Usage: tools/build_goose_nocmake.sh [goose-src dir] [output dir]
set -euo pipefail
SRC="${1:-build/goose-src}"
OUT="${2:-build/goose-nocmake}"
if [ ! -f "$SRC/CMakeLists.txt" ]; then
    echo "no Goose source at $SRC: run tools/pin_goose.sh first (it clones, then fails without cmake)" >&2
    exit 1
fi
TCC="$SRC/third_party/tinycc"
[ -f "$TCC/libtcc.c" ] || { echo "no vendored TinyCC at $TCC" >&2; exit 1; }
mkdir -p "$OUT/version" "$OUT/generated" "$OUT/include/api" "$OUT/obj"

GOOSE_CC="${GOOSE_CC:-gcc}"
GOOSE_CXX="${GOOSE_CXX:-g++}"
JOBS="${JOBS:-$(nproc 2>/dev/null || echo 2)}"

echo "goose source: $SRC at $(git -C "$SRC" rev-parse --short HEAD 2>/dev/null || echo unknown)"

# --- the files cmake would generate ----------------------------------------------
VERSION_TEXT="$(git -C "$SRC" describe --tags --always --dirty 2>/dev/null || echo unknown)"
printf '#define GOOSE_VERSION "%s"\n' "$VERSION_TEXT" > "$OUT/version/goose_version.h"
echo "version: $VERSION_TEXT"

python3 - "$SRC" "$OUT" <<'PY'
import re, sys
src, out = sys.argv[1], sys.argv[2]

# generated/builtin_packages.h: the blessed table as a raw string, and an empty
# package table (this build compiles no packages into the compiler).
blessed = open(f"{src}/src/blessed.txt").read()
rows = []
for line in blessed.splitlines():
    line = re.sub(r"#.*", "", line).strip()
    if not line:
        continue
    parts = re.split(r"[ \t]+", line)
    if len(parts) != 4:
        sys.exit(f"src/blessed.txt: a row has {len(parts)} fields, not 4: {line}")
    rows.append(parts)
with open(f"{out}/generated/builtin_packages.h", "w") as f:
    f.write("// Generated by tools/build_goose_nocmake.sh, as cmake/package.cmake writes\n")
    f.write("// it: the blessed table and the packages compiled into this compiler.\n")
    f.write("#pragma once\n\nnamespace goose {\n\n")
    f.write('inline const char *blessed_table = R"GSBL(' + blessed + ')GSBL";\n\n')
    f.write("inline const BuiltinPackage builtin_packages[] = {\n")
    f.write("    { nullptr, nullptr, nullptr, nullptr },\n};\n\n}  // namespace goose\n")
print(f"blessed: {len(rows)} rows")

# jit_symbols.inc: every GS_API function, as GS_JIT_SYMBOL(name).
names = []
for header in ("runtime.h", "runtime_ext.h"):
    try:
        text = open(f"{src}/src/runtime/{header}").read()
    except FileNotFoundError:
        continue
    for line in text.splitlines():
        if not line.startswith("GS_API "):
            continue
        m = re.search(r"(gs_[A-Za-z0-9_]+)\(", line)
        if m:
            names.append(m.group(1))
with open(f"{out}/jit_symbols.inc", "w") as f:
    for n in names:
        f.write(f"GS_JIT_SYMBOL({n})\n")
print(f"jit symbols: {len(names)}")
PY

# include/config.h: what TinyCC's own configure would have written.
TCC_VERSION="$(tr -d ' \r\n' < "$TCC/VERSION")"
cat > "$OUT/include/config.h" <<EOF
/* Generated by tools/build_goose_nocmake.sh, as cmake/libtcc.cmake writes it. */
#define TCC_VERSION "$TCC_VERSION"
#define CONFIG_TCC_PREDEFS 0
#define CONFIG_TCC_BACKTRACE 0
#define CONFIG_TCC_BCHECK 0
#define CONFIG_TCC_SYSINCLUDEPATHS "{B}/include"
#define CONFIG_TCC_CRTPREFIX "{B}"
#define CONFIG_TCC_LIBPATHS "{B}"
EOF
cp "$TCC/libtcc.h" "$OUT/include/api/libtcc.h"

# --- the objects ---------------------------------------------------------------
build_one() {   # output, then the command
    local obj="$1"; shift
    if [ -f "$obj" ] && [ "$obj" -nt "$SRC" ]; then :; fi
    "$@"
}

( build_one "$OUT/obj/libtcc.o" "$GOOSE_CC" -std=gnu99 -O2 -fPIC -DONE_SOURCE=1 \
      -DTCC_TARGET_X86_64 -I"$OUT/include" -I"$TCC" -c "$TCC/libtcc.c" -o "$OUT/obj/libtcc.o" ) &
( build_one "$OUT/obj/shaderc.o" "$GOOSE_CC" -std=gnu99 -O2 -I"$SRC/third_party/cute_spirv" \
      -c "$SRC/src/shaderc.c" -o "$OUT/obj/shaderc.o" ) &
( build_one "$OUT/obj/jit_runtime.o" "$GOOSE_CC" -std=gnu99 -O2 -I"$OUT" -I"$SRC/src" \
      -c "$SRC/src/jit_runtime.c" -o "$OUT/obj/jit_runtime.o" ) &
wait
echo "objects: $(ls "$OUT/obj" | tr '\n' ' ')"

# --- the compiler --------------------------------------------------------------
CPP_SOURCES=("$SRC"/src/*.cpp)
echo "compiling ${#CPP_SOURCES[@]} C++ sources"
printf '%s\n' "${CPP_SOURCES[@]}" | xargs -P "$JOBS" -I{} sh -c \
    'obj="'"$OUT"'/obj/$(basename {} .cpp).o"; '"$GOOSE_CXX"' -std=c++20 -O1 -w \
     -I"'"$SRC"'/src" -I"'"$SRC"'/third_party/subprocess" -I"'"$OUT"'/version" \
     -I"'"$OUT"'/generated" -I"'"$SRC"'/third_party/cute_spirv" -I"'"$OUT"'/include/api" \
     -c "{}" -o "$obj"'

"$GOOSE_CXX" -o "$OUT/goose" "$OUT"/obj/*.o -lpthread -ldl -lm
echo "built $OUT/goose ($(stat -c%s "$OUT/goose" 2>/dev/null || echo '?') bytes)"
"$OUT/goose" --version
if "$OUT/goose" --help 2>&1 | grep -qiE 'providers|goose up|migrat'; then
    echo "ERROR: this is not aardappel/goose" >&2
    exit 1
fi
echo "identity check: this is aardappel/goose (no providers/up commands)"
