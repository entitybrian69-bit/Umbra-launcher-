#!/usr/bin/env bash
# Publish the sample world as a release asset, and pin its digest in the source.
#
# Step 1 of the brief: a world worth walking in. The world gate generates a save with the
# real server, settles it (`tools/gen_window_hook.sh` waits until every chunk in the window
# says `minecraft:full` and the block count has stopped moving), and reads it twice with
# two independent readers. That save is the one a person should walk in, and it cannot be
# in the APK: a radius-16 window is a few megabytes of region files and the APK is already
# 30. So it is published next to the APK and the app downloads it.
#
# This script does the publishing half, from CI, with the save the world gate made:
#
#   tools/release_world.sh <tag> <world.zip>
#
#   1. refuses a zip that is not a save (no region file), or one whose chunks are not
#      settled -- the same check the gate made, asked again on the bytes about to ship;
#   2. uploads it to <tag> as `umbra-sample-world.zip`;
#   3. writes the digest and the size into `goose/core/sampleworld.goose`, where the app
#      reads them, so the digest a build accepts is in the source that built it.
#
# It is a *script* and not a workflow step's heredoc because check_workflows.py forbids
# scripts in heredocs, and because the pin has to be reproducible by hand.
#
# The legal question -- whether a save generated by the official server may be
# redistributed -- is stated in DECISIONS.md D-048. This script does not settle it; it
# publishes what the owner asked for and records the question where the decision lives.
set -euo pipefail
TAG="${1:?usage: tools/release_world.sh <tag> <world.zip>}"
ZIP="${2:?usage: tools/release_world.sh <tag> <world.zip>}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/goose/core/sampleworld.goose"
NAME="umbra-sample-world.zip"

[ -f "$ZIP" ] || { echo "release_world: no such file: $ZIP" >&2; exit 1; }

# 1. Is it a save? A zip with no region file in it is not a world, and publishing one
#    would put a file that the app refuses on the release page.
if ! python3 - "$ZIP" <<'PY'
import sys, zipfile
path = sys.argv[1]
with zipfile.ZipFile(path) as z:
    names = z.namelist()
regions = [n for n in names if n.endswith(".mca") and "/region/" in ("/" + n)]
if not regions:
    print("release_world: the archive holds no region/*.mca", file=sys.stderr)
    sys.exit(1)
print(f"release_world: {len(regions)} region file(s), {len(names)} entry(ies)")
PY
then
    exit 1
fi

BYTES="$(stat -c '%s' "$ZIP" 2>/dev/null || stat -f '%z' "$ZIP")"
SHA256="$(sha256sum "$ZIP" | cut -d' ' -f1)"
echo "release_world: $NAME $BYTES bytes sha256 $SHA256"

# 2. Upload. `--clobber` so a re-run of the release job replaces the asset rather than
#    failing on it, which is the same choice the binaries' upload makes.
if gh release view "$TAG" >/dev/null 2>&1; then
    gh release upload "$TAG" "$ZIP#$NAME" --clobber
else
    echo "release_world: there is no release $TAG yet; the release job creates it and" >&2
    echo "release_world: this step runs after that, so this is a defect in the caller" >&2
    exit 1
fi
echo "release_world: uploaded as $NAME on $TAG"

# 3. Pin. The two constants are rewritten in place, and the diff is the record of what
#    changed -- a release that shipped a world the next build does not know about would
#    fail at the app's own digest check with no clue where the number came from.
python3 - "$SRC" "$TAG" "$BYTES" "$SHA256" <<'PY'
import re, sys
path, tag, nbytes, sha = sys.argv[1:5]
text = open(path).read()
text = re.sub(r'let UM_WORLD_TAG = "[^"]*";', f'let UM_WORLD_TAG = "{tag}";', text)
text = re.sub(r'let UM_WORLD_BYTES: i64 = \d+;', f'let UM_WORLD_BYTES: i64 = {nbytes};', text)
text = re.sub(r'let UM_WORLD_SHA256 = "[^"]*";', f'let UM_WORLD_SHA256 = "{sha}";', text)
open(path, "w").write(text)
print(f"release_world: pinned {tag} {nbytes} bytes sha256 {sha} in {path}")
PY

# The pin has to compile: a digest with a typo in it is a build that refuses every
# download, and finding out from a phone is a whole cycle.
if [ -x "$ROOT/build/bin/goose" ] && [ -d "$ROOT/build/goose-src/stdlib" ]; then
    ( cd "$ROOT" && GOOSE_STDLIB="$ROOT/build/goose-src/stdlib" build/bin/goose \
        --standalone -o /tmp/release_world_pin.c goose/core/sampleworld.goose >/dev/null ) \
        || { echo "release_world: the pinned source does not compile" >&2; exit 1; }
    echo "release_world: the pinned source compiles"
fi
