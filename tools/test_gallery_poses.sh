#!/usr/bin/env bash
# The gallery's two silent failure modes, proved on the host.
#
# The emulator run is the only place the gallery runs for real, and it takes forty minutes
# to say anything. Two of its failures were decisions a laptop can check in a second, and
# both of them read as a pass until someone looked at the picture:
#
#   1. `tools/gallery_poses.py` picked the camera's height out of a section *index*. Section
#      19 means "somewhere in y 304..319", all of it air above a y-91 hilltop, and run
#      44938399066 put the gallery at y 320.01 and photographed the sky. The fix reads the
#      blocks; this guard proves the poses land on the ground, and that the reader agrees
#      with the second reader (`tools/world_oracle.py`) about where the ground is.
#
#   2. the shot gate was `stat -c%s` against 20 000 bytes. A valid sky shot is 14 581 bytes,
#      so a *correct* pose failed -- and six identical pictures of nothing would have
#      passed. This guard feeds `tools/check_gallery_shot.py` a real sky frame, a real
#      ground frame and a pair of copies, and requires it to reject the first and the pair.
#
# usage: tools/test_gallery_poses.sh      (exit 0 = both behaviours hold)
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT" || exit 1

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
fail=0

check() {
    local what="$1" want="$2"; shift 2
    if "$@" > "$TMP/out" 2>&1; then got=0; else got=1; fi
    if [ "$got" = "$want" ]; then
        printf 'ok   %-56s %s\n' "$what" "$(tail -1 "$TMP/out")"
    else
        printf 'FAIL %-56s exit %s, wanted %s: %s\n' "$what" "$got" "$want" \
            "$(tail -2 "$TMP/out" | tr '\n' ' ')"
        fail=1
    fi
}

# ---- 1. the poses land on the ground -------------------------------------------------
python3 tools/make_test_world.py "$TMP/world" 4 > "$TMP/gen.log" 2>&1 \
    || { echo "FAIL: the test world could not be generated: $(tail -2 "$TMP/gen.log" | tr '\n' ' ')"; exit 1; }

python3 tools/gallery_poses.py "$TMP/world" --out "$TMP/poses.txt" > "$TMP/poses.log" 2>&1
if [ $? -ne 0 ]; then
    echo "FAIL: no poses could be placed in the test world: $(tail -2 "$TMP/poses.log" | tr '\n' ' ')"
    exit 1
fi
printf '     %s\n' "$(tr '\n' ' ' < "$TMP/poses.txt")"

# The test world's ground is generated by `surface()`: y 61..65 at its highest, never above
# 66. A pose above 80 is a pose like 44938399066's -- a section index read as a height.
while read -r pose x y z yaw pitch; do
    case "$pose" in
        sky) limit=90 ;;   # explicitly above the ground
        *)   limit=80 ;;
    esac
    if python3 -c "import sys; sys.exit(0 if float('$y') <= $limit else 1)"; then
        printf 'ok   %-56s y %s <= %s\n' "pose $pose is at ground height" "$y" "$limit"
    else
        printf 'FAIL %-56s y %s is above %s, which this world does not have\n' \
            "pose $pose is at ground height" "$y" "$limit"
        fail=1
    fi
done < "$TMP/poses.txt"

# Six poses, and the two that need water and logs are the two that used to be unreachable
# once the reader was wrong.
count="$(wc -l < "$TMP/poses.txt")"
if [ "$count" -eq 6 ]; then
    printf 'ok   %-56s %s of six\n' "every pose has a place in this save" "$count"
else
    printf 'FAIL %-56s %s of six: %s\n' "every pose has a place in this save" "$count" \
        "$(grep -h 'nothing for it' "$TMP/poses.log" | tr '\n' ' ')"
    fail=1
fi

# The pose must agree with the other reader about where the ground is. `world_oracle.py`
# counts blocks per y over the same files; if the gallery's `hills` y is not a y the oracle
# has blocks at (with air above it), one of the two is reading the save differently.
python3 tools/world_oracle.py "$TMP/world" "$TMP/oracle.txt" 0 > "$TMP/oracle.log" 2>&1 \
    && python3 - "$TMP/poses.txt" "$TMP/oracle.txt" <<'PY'
import sys
poses = [l.split() for l in open(sys.argv[1]) if l.strip()]
top, total = {}, 0
for line in open(sys.argv[2]):
    if line.startswith("detail "):
        _, x, y, z, name = line.split()
        total += 1
        key = (int(x) // 16, int(z) // 16)
        top[key] = max(top.get(key, -999), int(y))
# What the pose has to agree with: the highest block the other reader sees in that column.
# `cave` is deliberately under the ground and `sky` deliberately above it.
bad = []
for name, x, y, z, yaw, pitch in poses:
    if name in ("cave", "sky"):
        continue
    key = (int(float(x)) // 16, int(float(z)) // 16)
    if key not in top:
        bad.append(f"{name} is in a column the oracle has no blocks in")
        continue
    feet = float(y)
    if not (top[key] < feet <= top[key] + 1.5):
        bad.append(f"{name} feet {feet:.2f} is not just above that column's top block "
                   f"({top[key]})")
if total == 0:
    bad.append("the oracle found no blocks in the same save")
if bad:
    print("FAIL: " + "; ".join(bad))
    sys.exit(1)
print(f"ok: the oracle agrees: {total} blocks, and every ground pose stands on its column's top")
PY
[ $? -eq 0 ] || fail=1

# The reader has to cope with both palette flavours and both packings -- that is what made
# the block decoder worth writing instead of the byte hunt. `make_test_world.py` can write
# each, so the poses are placed in all of them and must land the same way.
for flavour in "4 compound contiguous" "4 string padded"; do
    # shellcheck disable=SC2086
    set -- $flavour
    dir="$TMP/world-$2-$3"
    if python3 tools/make_test_world.py "$dir" "$1" "$2" "$3" > "$TMP/gen-$2-$3.log" 2>&1; then
        if python3 tools/gallery_poses.py "$dir" --out "$TMP/p-$2-$3.txt" > "$TMP/p-$2-$3.log" 2>&1 \
           && [ "$(wc -l < "$TMP/p-$2-$3.txt")" -eq 6 ] \
           && awk '{ if ($1 != "sky" && $3 > 80) bad = 1 } END { exit bad ? 1 : 0 }' "$TMP/p-$2-$3.txt"; then
            printf 'ok   %-56s 6 pose(s), none above the ground\n' "the $2/$3 palette flavour reads"
        else
            printf 'FAIL %-56s %s\n' "the $2/$3 palette flavour reads" \
                "$(tail -2 "$TMP/p-$2-$3.log" | tr '\n' ' ')"
            fail=1
        fi
    else
        printf 'skip %-56s the generator does not write this flavour\n' "the $2/$3 palette flavour reads"
    fi
done

# ---- 1b. two layouts with the same file names ------------------------------------------
# A 26.3 server leaves `world/region/r.0.0.mca` from spawn preparation beside the real
# terrain at `world/dimensions/minecraft/overworld/region/r.0.0.mca`. They are different
# worlds with identical names, `zip_world.py` refuses both at once for that reason, and run
# 44951752864 posed the camera 33 blocks above the ground the renderer had drawn because the
# pose tool chose the shallow -- stale -- one.
#
# So the tool must prefer the dimensions layout even though it is deeper, and it must read
# the *archive* the phone was given when it is handed one.
mkdir -p "$TMP/two/world/dimensions/minecraft/overworld"
cp -r "$TMP/world/region" "$TMP/two/world/dimensions/minecraft/overworld/region"
# The stale layout: the same file names, from a different generation, at the top level where
# a 26.3 server leaves spawn-preparation terrain.
python3 tools/make_test_world.py "$TMP/stale" 4 > /dev/null 2>&1
mkdir -p "$TMP/two/world/region"
cp "$TMP/stale/region/r.0.0.mca" "$TMP/two/world/region/r.0.0.mca"
python3 - "$TMP/two/world" "$TMP/two/world/dimensions/minecraft/overworld/region" "$TMP/two/world/region" <<'PY'
import sys
sys.path.insert(0, "tools")
import gallery_poses as g
want = sys.argv[2].replace("\\", "/")
got = g.find_region_dir(sys.argv[1]).replace("\\", "/")
if got != want:
    print(f"FAIL: the tool chose {got}, not the dimensions layout {want}")
    sys.exit(1)
print(f"ok: two layouts present, and the dimensions one won: {got}")
PY
[ $? -eq 0 ] && printf 'ok   %-56s %s\n' "a stale layout with the same names loses" "dimensions/ wins" \
            || { printf 'FAIL %-56s it chose the stale layout\n' "a stale layout with the same names loses"; fail=1; }

# And the same save, zipped the way the workflow zips it, must read identically -- the
# archive is what the phone opens, so the archive is what the poses should come from.
python3 tools/zip_world.py "$TMP/world.zip" "$TMP/world/region/r.0.0.mca" \
    > "$TMP/zip.log" 2>&1
if [ -f "$TMP/world.zip" ]; then
    python3 tools/gallery_poses.py "$TMP/world.zip" --out "$TMP/p-zip.txt" > "$TMP/p-zip.log" 2>&1
    if [ -s "$TMP/p-zip.txt" ] && diff -q "$TMP/poses.txt" "$TMP/p-zip.txt" > /dev/null 2>&1; then
        printf 'ok   %-56s the same six poses as the directory\n' "the archive reads like the save"
    else
        printf 'FAIL %-56s %s\n' "the archive reads like the save" \
            "$(tail -2 "$TMP/p-zip.log" | tr '\n' ' ')"
        fail=1
    fi
else
    printf 'FAIL %-56s zip_world refused it: %s\n' "the archive reads like the save" \
        "$(tail -1 "$TMP/zip.log")"
    fail=1
fi

# ---- 2. the shot gate ------------------------------------------------------------------
# A sky frame: one flat colour and the nav bar, which is exactly the 14 581-byte file from
# run 44938399066 (99.8% of that frame was the one sky colour). This must be rejected, and
# the reason must be the flatness -- so `--min-colours 2` here, and a perfectly uniform
# frame below for the colour floor the default applies.
python3 - "$TMP/sky.png" <<'PY'
import struct, sys, zlib
w, h = 480, 270
rows = bytearray()
for y in range(h):
    rows.append(0)
    for x in range(w):
        nav = (x > w - 24) and ((y // 60) % 2 == 0) and ((x // 6) % 3 == 0) and y < h - 40
        rows += bytes((255, 255, 255)) if nav else bytes((140, 179, 235))
def chunk(kind, body):
    return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF)
png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) \
    + chunk(b"IDAT", zlib.compress(bytes(rows), 9)) + chunk(b"IEND", b"")
open(sys.argv[1], "wb").write(png)
PY
cp "$TMP/sky.png" "$TMP/sky-copy.png"
check "a flat sky frame is rejected"                  1 \
    python3 tools/check_gallery_shot.py "$TMP/sky.png" --size 480x270 --min-colours 2
check "the rejection names the flatness, not the size" 0 \
    sh -c "python3 tools/check_gallery_shot.py '$TMP/sky.png' --size 480x270 --min-colours 2 2>&1 | grep -q 'one colour'"
check "a shot of the wrong surface is rejected"       1 \
    python3 tools/check_gallery_shot.py "$TMP/sky.png" --size 1920x1080 --min-colours 2

# A frame with nothing drawn on it at all -- the surface before the first draw, which is a
# valid PNG of one colour and is not a picture of anything.
python3 - "$TMP/null.png" <<'PY'
import struct, sys, zlib
w, h = 480, 270
rows = bytearray()
for _y in range(h):
    rows.append(0)
    rows += bytes((0, 0, 0)) * w
def chunk(kind, body):
    return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF)
png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) \
    + chunk(b"IDAT", zlib.compress(bytes(rows), 9)) + chunk(b"IEND", b"")
open(sys.argv[1], "wb").write(png)
PY
check "a single-colour frame is rejected as blank"    1 \
    python3 tools/check_gallery_shot.py "$TMP/null.png" --size 480x270

# A ground frame: terrain over the bottom two thirds, sky above, a different picture from the
# sky one. It must pass, and it must pass against the sky frame as "different".
python3 - "$TMP/ground.png" <<'PY'
import struct, sys, zlib
w, h = 480, 270
rows = bytearray()
for y in range(h):
    rows.append(0)
    for x in range(w):
        if y > h * 2 // 3:
            v = (40 + (x * 7 + y * 3) % 60, 90 + (x * 5) % 50, 30 + (y * 11) % 40)
        else:
            v = (140, 179, 235)
        rows += bytes(v)
def chunk(kind, body):
    return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF)
png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) \
    + chunk(b"IDAT", zlib.compress(bytes(rows), 9)) + chunk(b"IEND", b"")
open(sys.argv[1], "wb").write(png)
PY
check "a posed frame over ground passes"              0 python3 tools/check_gallery_shot.py "$TMP/ground.png" --size 480x270
# Two copies of a frame that is *not* blank: the flatness rule passes, so what rejects this
# pair is the signature -- six poses could otherwise be one pose photographed six times.
cp "$TMP/ground.png" "$TMP/ground-copy.png"
check "two copies of one frame are rejected"          1 \
    python3 tools/check_gallery_shot.py "$TMP/ground.png" --differs-from "$TMP/ground-copy.png"
check "and the reason is the pictures matching"       0 \
    sh -c "python3 tools/check_gallery_shot.py '$TMP/ground.png' --differs-from '$TMP/ground-copy.png' 2>&1 | grep -q 'are the same picture'"
check "it is a different picture from the sky frame"  0 python3 tools/check_gallery_shot.py "$TMP/ground.png" --size 480x270 --differs-from "$TMP/sky.png"

[ "$fail" = 0 ] && echo "PASS: the poses land on the ground and the shot gate rejects a blank frame" \
                || echo "FAILED: the gallery's host checks did not pass"
exit "$fail"
