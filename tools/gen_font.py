out = ["// Generated by tools/gen_font.py: one 8x8 byte per glyph, bit 0 is the",
       "// leftmost pixel, for ASCII 32..126. Do not edit by hand.",
       "#pragma once",
       "#include <stdint.h>",
       "static const uint8_t UMBRA_FONT8X8[95][8] = {"]
for code in range(32, 127):
    ch = chr(code)
    rows = GLYPHS.get(ch, GLYPHS.get(ch.upper(), ["     "]*7))
    rows = (rows + ["     "]*7)[:7]
    bytes_ = []
    for r in rows:
        b = 0
        for i, c in enumerate(r[:5]):
            if c != ' ':
                b |= 1 << i
        bytes_.append(f"0x{b:02X}")
    bytes_.append("0x00")
    out.append("    {" + ",".join(bytes_) + "},  // " + (ch if ch not in ('\\', '"') else ' '))
out.append("};")
path = os.path.join(os.path.dirname(__file__), '..', 'platform', 'shared', 'umbra_font.h')
open(path, 'w').write("\n".join(out) + "\n")
print(f"wrote {path}: {len(GLYPHS)} glyphs defined, 95 cells")
